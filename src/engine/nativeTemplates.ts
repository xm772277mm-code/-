function formatFloatArray(arr: Float32Array, name: string): string {
  const lines: string[] = [];
  lines.push(`constexpr float ${name}[${arr.length}] = {`);
  for (let i = 0; i < arr.length; i += 12) {
    const slice = Array.from(arr.subarray(i, i + 12))
      .map((v) => v.toFixed(6) + "f")
      .join(", ");
    lines.push(`    ${slice}${i + 12 < arr.length ? "," : ""}`);
  }
  lines.push("};");
  return lines.join("\n");
}

